/**
 * Country dial codes for the onboarding phone field. `iso` is the ISO-3166
 * alpha-2 code (matches what IP-geolocation returns, so we can map a detected
 * country straight to a default), `dial` is the E.164 calling code.
 *
 * Covers every ISO-3166-1 country plus dialable territories (uninhabited or
 * phone-less codes like AQ are left out). NANP members (US, Canada, most of
 * the Caribbean) all share `+1` — E.164 doesn't distinguish them, the area
 * code does — so several entries carry the same dial code and `iso` is the
 * only unique key. The picker sorts alphabetically at render time; this file
 * is kept A→Z purely for maintainability.
 */
export interface Country {
  iso: string;
  name: string;
  dial: string;
  /**
   * Valid national-number digit counts (excluding the dial code). Used to
   * validate the phone field against the picked country. Omit where the
   * length varies too widely to pin down — callers fall back to a generic
   * 7–15 digit range in that case.
   */
  nsnLengths?: number[];
}

